# B 附加：核对原文“1/5810”的口径。假设：10 个 NIST 种子各自“5 个 32 位字的最高位全为 0”的概率为 2^-5，
# 求 10 个种子中至少 4 个满足的二项概率。
from math import comb
p = 2 ** -5
s = sum(comb(10, j) * p**j * (1 - p) ** (10 - j) for j in range(4, 11))
print("P(X>=4 of 10) =", s, " 1/P =", 1 / s)
print("P(指定的 4 个种子 20 个字最高位全为 0) = 2^-20 =", 2**-20, " 1/P =", 2**20)
